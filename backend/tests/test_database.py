from __future__ import annotations

import io
import tempfile
import unittest
from datetime import UTC, datetime
from pathlib import Path

from backend.app import database
from backend.app.adapters import AdapterSnapshot
from backend.app.main import route_candidates
from backend.app.models import FileCreate, JobCreate, PrinterCreate


class DatabaseTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary_directory = tempfile.TemporaryDirectory()
        self.original_data_directory = database.DATA_DIRECTORY
        self.original_database_path = database.DATABASE_PATH
        self.original_files_directory = database.FILES_DIRECTORY
        database.DATA_DIRECTORY = Path(self.temporary_directory.name)
        database.DATABASE_PATH = database.DATA_DIRECTORY / "fleet.db"
        database.FILES_DIRECTORY = database.DATA_DIRECTORY / "files"
        database.initialize()

    def tearDown(self) -> None:
        database.DATA_DIRECTORY = self.original_data_directory
        database.DATABASE_PATH = self.original_database_path
        database.FILES_DIRECTORY = self.original_files_directory
        self.temporary_directory.cleanup()

    def test_printer_and_job_are_persisted_to_the_local_queue(self) -> None:
        printer = database.create_printer(
            PrinterCreate(
                name="Forge North",
                manufacturer="Bambu Lab",
                model="P1S",
                adapter_type="bambu_lan",
                host="192.168.1.88",
            )
        )
        job = database.create_job(
            JobCreate(
                name="Fixture arm",
                filename="fixture-arm.3mf",
                target_printer_id=printer.id,
                material="PETG · Orange",
                estimated_minutes=90,
            )
        )

        dashboard = database.dashboard()

        self.assertEqual([item.id for item in dashboard.printers], [printer.id])
        self.assertEqual([item.id for item in dashboard.jobs], [job.id])
        self.assertEqual(dashboard.jobs[0].queue_position, 1)
        self.assertEqual(len(dashboard.activity), 2)

    def test_connection_snapshot_is_saved_without_storing_a_secret(self) -> None:
        printer = database.create_printer(
            PrinterCreate(
                name="Forge West",
                manufacturer="Prusa",
                model="MK4",
                adapter_type="prusalink",
                host="printer.local",
            )
        )
        snapshot = AdapterSnapshot(
            state="printing",
            percent_complete=24,
            active_job="enclosure.3mf",
            bed_temp=60,
            nozzle_temp=215,
            note="PRINTING",
            seen_at=datetime.now(UTC),
        )
        saved = database.configure_connection(
            printer.id,
            adapter_type="prusalink",
            host="printer.local",
            credential_id="printer:test",
            capabilities=["telemetry", "file_transfer", "job_control"],
            snapshot=snapshot,
        )
        self.assertIsNotNone(saved)
        self.assertEqual(saved.connection_state, "connected")
        self.assertEqual(saved.active_job, "enclosure.3mf")
        self.assertEqual(saved.capabilities, ["telemetry", "file_transfer", "job_control"])
        self.assertEqual(database.credential_id_for_printer(printer.id), "printer:test")

    def test_upload_is_stored_locally_with_a_checksum(self) -> None:
        contents = b"; generated by test\nG28\n"
        stored = database.store_upload(
            FileCreate(name="Calibration cube", filename="cube.gcode", file_type="gcode"),
            "cube.gcode",
            io.BytesIO(contents),
        )

        result = database.stored_file(stored.id)

        self.assertIsNotNone(result)
        record, path = result
        self.assertEqual(record.size_bytes, len(contents))
        self.assertEqual(path.read_bytes(), contents)
        self.assertEqual(len(record.sha256 or ""), 64)

    def test_route_candidates_prefers_the_ready_printer_with_loaded_material(self) -> None:
        matching = database.create_printer(
            PrinterCreate(
                name="PETG ready",
                manufacturer="Example",
                model="One",
                adapter_type="moonraker",
                material="PETG - Black",
                supported_materials=["PLA", "PETG"],
            )
        )
        alternate = database.create_printer(
            PrinterCreate(
                name="PETG available",
                manufacturer="Example",
                model="Two",
                adapter_type="moonraker",
                material="PLA - White",
                supported_materials=["PLA", "PETG"],
            )
        )
        snapshot = AdapterSnapshot(
            state="ready", percent_complete=None, active_job=None, bed_temp=None,
            nozzle_temp=None, note=None, seen_at=datetime.now(UTC),
        )
        for printer in (matching, alternate):
            database.configure_connection(
                printer.id, adapter_type="moonraker", host=f"{printer.id}.local",
                credential_id=None, capabilities=["telemetry", "file_transfer", "job_control"], snapshot=snapshot,
            )
        job = database.create_job(JobCreate(name="PETG part", filename="part.gcode", material="PETG - Black"))

        candidates = route_candidates(job)
        routed = database.route_job(job.id, candidates[0].printer_id, candidates[0].reason)

        self.assertEqual(candidates[0].printer_id, matching.id)
        self.assertEqual(candidates[0].score, 100)
        self.assertEqual(routed.target_printer_id, matching.id)
        self.assertEqual(routed.delivery_state, "not_ready")
